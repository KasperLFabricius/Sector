def test_checkout_install_baseline_triggers_commands_and_order_are_exact():
    workflow = _workflow()
    _step(workflow, CHECKOUT_STEP)["with"]["fetch-depth"] = 1
    with pytest.raises(DependencyAuditError, match="accepted Git baseline"):
        validate_workflow(_workflow_text(workflow))

    workflow = _workflow()
    _step(workflow, INSTALL_STEP)["run"] = "python -m pip install pip-audit"
    with pytest.raises(DependencyAuditError, match="locked QA install"):
        validate_workflow(_workflow_text(workflow))

    workflow = _workflow()
    _step(workflow, VALIDATE_STEP)["env"][BASELINE_ENV] = "HEAD^"
    with pytest.raises(DependencyAuditError, match="baseline expression"):
        validate_workflow(_workflow_text(workflow))

    workflow = _workflow()
    triggers = workflow.get("on", workflow.get(True))
    triggers["pull_request"] = {"paths": ["requirements*.txt"]}
    with pytest.raises(DependencyAuditError, match="unfiltered"):
        validate_workflow(_workflow_text(workflow))

    workflow = _workflow()
    steps = workflow["jobs"]["test"]["steps"]
    executor = steps.pop(steps.index(_step(workflow, EXECUTE_STEP)))
    steps.insert(steps.index(_step(workflow, FULL_TEST_STEP)) + 1, executor)
    with pytest.raises(DependencyAuditError, match="step order"):
        validate_workflow(_workflow_text(workflow))

    workflow = _workflow()
    assert _step(workflow, INSTALL_STEP)["run"] == INSTALL_COMMAND
    assert _step(workflow, VALIDATE_STEP)["env"] == {
        BASELINE_ENV: BASELINE_EXPRESSION
    }
    assert _step(workflow, CHECKOUT_STEP)["uses"] == CHECKOUT_ACTION
    assert _step(workflow, PREPARE_STEP)["shell"] == "pwsh"
